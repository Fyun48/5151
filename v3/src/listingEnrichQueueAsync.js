async function withFallback(options, runPostgres, runSqlite) {
  const driver = options.driver || resolveDbDriver();
  if (driver !== "postgres") return runSqlite();
  try {
    if (options.exec) return await runPostgres(options.exec);
    const pgDriver = options.pgDriver || (await sharedPgDriver());
    const exec = (sql, params = []) => pgDriver.query(toPostgresSql(sql), params).then((res) => res.rows);
    return await runPostgres(exec);
  } catch (error) {
    if (options.strict) throw error;
    return runSqlite();
  }
}

// ---- 2.3b 第二段：寫入路徑的共用工具 -----------------------------------------

function firstRow(raw) {
  const rows = Array.isArray(raw) ? raw : (raw && raw.rows) || [];
  return rows[0] || null;
}

// PG 的 query() 回 { rows, rowCount }；node:sqlite 的 run() 回 { changes }。
// 兩種形狀都正規化成 { rows, rowCount }，寫入路徑才判斷得出「有沒有生效」。
function normalizeResult(raw) {
  if (Array.isArray(raw)) return { rows: raw, rowCount: Number(raw.rowCount ?? raw.length) || 0 };
  const rows = (raw && raw.rows) || [];
  const changes = Number(raw && raw.changes);
  return { rows, rowCount: Number((raw && raw.rowCount) ?? (Number.isFinite(changes) ? changes : rows.length)) || 0 };
}

// 每次呼叫都帶著 sqliteHandle：PG 分支才有 SQLite schema 可以鏡射建表。
function withConn(options, conn) {
  if (!conn || options.sqliteHandle) return options;
  return { ...options, sqliteHandle: conn };
}

// PG 端這三張表的準備：鏡射建表 → 重新對齊 identity 序號 → 補欄位。
// 序號那一步不能省：影子站是「帶 id 匯入」的，PostgreSQL 不會因為帶 id 的 INSERT 推進
// GENERATED BY DEFAULT AS IDENTITY 序號，第一次不帶 id 的寫入就會撞 pkey
// （2026-09-23 實測：listing_enrich_jobs 有 9145 列，序號還停在 1）。
export async function preparePgEnrichStore(pgDriver, sqliteDb) {
  await ensurePgSchema(pgDriver, sqliteDb, { tables: repo.LISTING_ENRICH_TABLES });
  await resyncIdentitySequences(pgDriver, sqliteDb, { tables: repo.LISTING_ENRICH_TABLES });
}

// 欄位探測：PostgreSQL 沒有 PRAGMA table_info()，改查 information_schema.columns；
// 缺的欄位才 ALTER TABLE（與 SQLite 端 ensureColumn 的目的一樣）。TEXT／INTEGER 語法兩邊相通。
export async function syncListingEnrichColumns(exec, runDdl) {
  const added = [];
  for (const mig of repo.LISTING_ENRICH_COLUMN_MIGRATIONS) {
    const probe = repo.columnProbeQuery(mig.table);
    const { rows } = await exec(probe.sql, probe.params);
    if (!(rows || []).some((row) => String(row.column_name) === mig.name)) {
      await runDdl(repo.addColumnQuery(mig.table, mig.name, mig.ddl).sql);
      added.push(`${mig.table}.${mig.name}`);
    }
  }
  return added;
}

// schema（表 ＋ 欄位）只準備一次：DDL 是 idempotent，但每個 entry point 都跑一次太浪費。
// 有真 driver 時以它為 key；只有注入 exec（測試／探針）時才用 exec 當 key。
const schemaReady = new WeakSet();

async function ensureEnrichSchemaOnce(exec, pgDriver, sqliteDb) {
  const key = pgDriver || exec;
  if (schemaReady.has(key)) return;
  if (pgDriver && sqliteDb) await preparePgEnrichStore(pgDriver, sqliteDb);
  await syncListingEnrichColumns(exec, (sql) => exec(sql, []));
  schemaReady.add(key);
}

// 寫入路徑的 withFallback：差別在 exec 回傳 { rows, rowCount }（回退語意與第一段相同），
// 另外會在第一次呼叫時把 PG schema 準備好（PG 端不走 schemaMigrations，所以由這裡負責）。
async function withFallbackCounted(options, runPostgres, runSqlite) {
  const driver = options.driver || resolveDbDriver();
  if (driver !== "postgres") return runSqlite();
  try {
    if (options.exec) {
      const injected = (sql, params = []) => Promise.resolve(options.exec(sql, params)).then(normalizeResult);
      await ensureEnrichSchemaOnce(injected, null, options.sqliteHandle);
      return await runPostgres(injected);
    }
    const pgDriver = options.pgDriver || (await sharedPgDriver());
    const exec = async (sql, params = []) => normalizeResult(await pgDriver.query(toPostgresSql(sql), params));
    await ensureEnrichSchemaOnce(exec, pgDriver, options.sqliteHandle);
    return await runPostgres(exec);
  } catch (error) {
    if (options.strict) throw error;
    return runSqlite();
  }
}


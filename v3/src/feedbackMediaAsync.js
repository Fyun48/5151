/** 在 `submitFeedbackAsync()` 的同一個 PG 交易內呼叫（`exec` 由呼叫端提供）。 */
export async function claimFeedbackAttachmentsAsync(exec, userId, ids, feedbackId, now = new Date()) {
  const list = [...new Set((Array.isArray(ids) ? ids : []).map((id) => Number(id)).filter((id) => Number.isInteger(id) && id > 0))];
  if (!list.length) return 0;
  const marks = list.map(() => "?").join(",");
  const ts = (now instanceof Date ? now : new Date(now)).toISOString();
  // 呼叫端傳進來的 exec 有兩種形狀（裸陣列 / `{rows,rowCount}`，feedbackAsync 的 tx 是後者），
  // 這裡一律用 `rowsOf()` 收斂，避免「明明改了卻比對到 undefined 長度」而誤丟 409。
  const rows = rowsOf(await exec(
    `UPDATE feedback_attachment SET feedback_id=?, claimed_at=?
     WHERE id IN (${marks}) AND user_id=? AND feedback_id=0 AND deleted_at IS NULL RETURNING id`,
    // 參數順序同同步版：feedback_id、claimed_at、id IN (…)、user_id。
    [Number(feedbackId), ts, ...list, Number(userId)],
  ));
  if (rows.length !== list.length) throw httpError("附件已失效，請重新上傳", 409, "attachment_stale");
  return list.length;
}


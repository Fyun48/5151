// 內容文件（條款／隱私權／各類規則）的 driver-aware 入口（PG 島嶼，2026-09-27）。
//
// 涵蓋的路由：
//   GET    /api/public/documents           列出必要文件（註冊條款、隱私權）
//   GET    /api/public/documents/:type     取目前生效的那一版
//   GET    /api/admin/documents            後台列表（含草稿）
//   GET    /api/admin/documents/:id        單筆 ＋ 稽核事件
//   GET    /api/admin/documents/:id/events 稽核事件
//   POST   /api/admin/documents            建立草稿
//   PATCH  /api/admin/documents/:id        更新草稿（已發布者只能改旗標）
//   POST   /api/admin/documents/:id/publish
//   POST   /api/admin/documents/:id/new-version
//   另外 `legalCopyFromDocuments()` 是多條路由（`/api/disclaimer`、`/api/me`、註冊流程…）
//   的共用卡點，一併移植。
//
// 🚨 **這一輪的方言難點：不可變性是用 SQLite TRIGGER 實作的。**
//
// `ensureContentDocumentSchema()`（contentDocuments.js:106）建了一個
// `content_documents_immutable` 触发器：`OLD.status = 'published'` 时，只要
// body／title／format／check_label／content_hash／version／document_type 有變就
// `RAISE(ABORT, 'published_document_immutable')`。
//
// **PG 完全不吃這個語法**（沒有 `IS NOT OLD.x`、沒有 `RAISE(ABORT)`）。要等價的話得寫
// plpgsql 函式 ＋ `CREATE TRIGGER ... EXECUTE FUNCTION`，而且 `IS NOT OLD.x` 要換成
// `IS DISTINCT FROM`。**這不是「有就好」的加固：它是一條真正的業務規則**
// （已發布的條款不能事後被改掉——那會讓使用者同意過的版本與畫面不一致），
// 少了它就等於 PG 上沒有這個保護。
//
// ⚠️ 第二個坑：`nextVersion()` 用 `MAX(version)`，PG 回的是 bigint 字串，要 `Number()`。

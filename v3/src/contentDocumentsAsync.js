export async function createDraftAsync(input = {}, { actorId = 0, now = new Date(), ...options } = {}) {
  if (!isPg(options)) return createDraftSync(sqliteHandle(), input, { actorId, now });
  const type = assertType(input.document_type);
  const fields = validatePayload(input); // 純驗證，兩邊共用同一份
  return withFallbackTx(options, async (exec) => {
    const version = Number(input.version) > 0 ? Number(input.version) : await nextVersionAsync(exec, type);
    if (await readByTypeVersion(exec, type, version)) throw httpError("這個版本號已存在", 409);
    const fingerprint = documentFingerprint({ document_type: type, version, ...fields });
    const row = firstRow(await exec(INSERT_DRAFT_SQL, [
      type, version, fields.title, fields.body, fields.format, fields.check_label,
      input.enabled === false ? 0 : 1,
      input.requires_reacceptance === true ? 1 : 0,
      input.effective_from || null,
      input.effective_until || null,
      fingerprint,
      Number(actorId) || null,
      iso(now),
      Number(input.supersedes_id) || null,
    ]));
    const doc = rowToDoc(row);
    await writeAudit(exec, {
      document_id: doc.id, document_type: type, version, action: "draft_create",
      actor_id: actorId, content_hash: fingerprint, now,
    });
    return doc;
  }, () => createDraftSync(sqliteHandle(), input, { actorId, now }));
}

export async function updateDraftAsync(id, input = {}, { actorId = 0, now = new Date(), ...options } = {}) {
  if (!isPg(options)) return updateDraftSync(sqliteHandle(), id, input, { actorId, now });
  return withFallbackTx(options, async (exec) => {
    const doc = await readById(exec, id);
    if (!doc) throw httpError("找不到文件", 404);
    if (doc.status === "published") {
      // 已發布版本**只能改旗標**，本文欄位一律拒絕（與同步版同義）。
      if (input.title != null || input.body != null || input.format != null || input.check_label != null) {
        throw httpError("已發布版本不可改本文；請建立新版本", 409);
      }
      await updatePublishedFlagsAsync(exec, doc, input, { actorId, now });
      return readById(exec, doc.id);
    }
    const fields = validatePayload({
      title: input.title ?? doc.title,
      body: input.body ?? doc.body,
      format: input.format ?? doc.format,
      check_label: input.check_label ?? doc.check_label,
    });
    const hash = documentFingerprint({ document_type: doc.document_type, version: doc.version, ...fields });
    await exec(UPDATE_DRAFT_SQL, [
      fields.title, fields.body, fields.format, fields.check_label,
      flagValue(input.enabled, doc.enabled),
      flagValue(input.requires_reacceptance, doc.requires_reacceptance),
      input.effective_from === undefined ? doc.effective_from : (input.effective_from || null),
      input.effective_until === undefined ? doc.effective_until : (input.effective_until || null),
      hash,
      doc.id,
    ]);
    await writeAudit(exec, {
      document_id: doc.id, document_type: doc.document_type, version: doc.version,
      action: "draft_update", actor_id: actorId, content_hash: hash, now,
    });
    return readById(exec, doc.id);
  }, () => updateDraftSync(sqliteHandle(), id, input, { actorId, now }));
}

// 同步版的 `input.x === false ? 0 : (input.x === true ? 1 : doc.x)`——三態：
// 沒帶就沿用舊值。抽出來讓兩處（草稿／已發布旗標）與同步版語意一致。
function flagValue(input, current) {
  if (input === false) return 0;
  if (input === true) return 1;
  return current ? 1 : 0;
}

async function updatePublishedFlagsAsync(exec, doc, input, { actorId, now }) {
  await exec(UPDATE_PUBLISHED_FLAGS_SQL, [
    flagValue(input.enabled, doc.enabled),
    flagValue(input.requires_reacceptance, doc.requires_reacceptance),
    input.effective_from === undefined ? doc.effective_from : (input.effective_from || null),
    input.effective_until === undefined ? doc.effective_until : (input.effective_until || null),
    doc.id,
  ]);
  await writeAudit(exec, {
    document_id: doc.id, document_type: doc.document_type, version: doc.version,
    action: "flags_update", actor_id: actorId, content_hash: doc.content_hash, now,
  });
}

export async function publishDocumentAsync(id, { actorId = 0, now = new Date(), ...options } = {}) {
  if (!isPg(options)) return publishDocumentSync(sqliteHandle(), id, { actorId, now });
  return withFallbackTx(options, async (exec) => {
    const doc = await readById(exec, id);
    if (!doc) throw httpError("找不到文件", 404);
    if (doc.status === "published") return doc; // 已發布 ⇒ 直接回，不重複寫稽核（同步版同義）
    await exec(PUBLISH_SQL, [iso(now), doc.id]);
    const published = await readById(exec, doc.id);
    await writeAudit(exec, {
      document_id: published.id, document_type: published.document_type, version: published.version,
      action: "publish", actor_id: actorId, content_hash: published.content_hash, now,
    });
    return published;
  }, () => publishDocumentSync(sqliteHandle(), id, { actorId, now }));
}

export async function createDraftFromPublishedAsync(id, { actorId = 0, now = new Date(), ...options } = {}) {
  if (!isPg(options)) return createDraftFromPublishedSync(sqliteHandle(), id, { actorId, now });
  const doc = await getDocumentByIdAsync(id, options);
  if (!doc) throw httpError("找不到文件", 404);
  if (doc.status !== "published") throw httpError("只能從已發布版本開新草稿", 400);
  return createDraftAsync({
    document_type: doc.document_type,
    title: doc.title,
    body: doc.body,
    format: doc.format,
    check_label: doc.check_label,
    enabled: true,
    requires_reacceptance: false,
    supersedes_id: doc.id,
  }, { actorId, now, ...options });
}

// 供測試與其他模組檢查「PG 上有沒有那條不可變規則」。
export async function publishedDocumentIsImmutable(pgDriverOrExec) {
  const exec = typeof pgDriverOrExec === "function"
    ? pgDriverOrExec
    : (sql, params = []) => pgDriverOrExec.query(toPostgresSql(sql), params).then((r) => r.rows);
  const row = firstRow(await exec(
    "SELECT 1 AS ok FROM pg_trigger WHERE tgname='content_documents_immutable' AND NOT tgisinternal",
  ));
  return Boolean(row);
}

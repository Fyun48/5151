// listingEnrichQueue.js requestClickRefresh()
export function requestClickRefreshAsync(conn, listing, via = "click", options = {}) {
  const opts = withConn(options, conn);
  return withFallbackCounted(
    opts,
    async (exec) => {
      if (!enrichEnqueueEligible(listing)) return { queued: false };
      const jobQuery = repo.enrichJobByPostIdQuery(listing.post_id);
      const prep = await repo.readPrepRow(exec, listing.post_id);
      const existing = firstRow(await exec(jobQuery.sql, jobQuery.params));
      const decision = requestClickPlan(prep, existing, listing, via);
      let job = existing;
      if (decision.enqueue) {
        await exec(decision.enqueue.sql, decision.enqueue.params);
        job = firstRow(await exec(jobQuery.sql, jobQuery.params));
      }
      return clickRefreshResult(decision, job);
    },
    () => requestClickRefreshSync(conn, listing, via),
  );
}

// listingEnrichQueue.js processListingEnrichBatch() 用的 bundle（helpers.enrichQueue）。
// 方法簽名刻意與同步函式一致（第一個參數都是 conn），所以 SQLite 模式就等於直接呼叫它們。
export function listingEnrichQueueFacade(conn, options = {}) {
  const opts = withConn(options, conn);
  const driver = opts.driver || resolveDbDriver();
  const useConn = (c) => c || conn;
  return {
    driver,
    seed: (c, seedOpts) => seedHousepriceEnrichJobsAsync(useConn(c), seedOpts, opts),
    claim: (c, args) => claimEnrichJobsAsync(useConn(c), args, opts),
    finish: (c, job, patch) => finishEnrichJobAsync(useConn(c), job, patch, opts),
    metric: (c, job, timings) => recordEnrichMetricAsync(useConn(c), job, timings, opts),
    ownsRun: (c, job) => jobStillOwnsRunAsync(useConn(c), job, opts),
    getPrep: (c, postId) => getListingPrepAsync(useConn(c), postId, opts),
    prepChecked: (c, args) => prepCheckedUpdateAsync(useConn(c), args, opts),
  };
}


// 單列搶單（PG：與 sync 的 claimOne 同一順序、同一份 SQL；名額分配共用 claimTakePlan）。
async function claimOneViaExec(exec, opts = {}, now = Date.now()) {
  const stamp = new Date(now).toISOString();
  const leaseUntil = new Date(now + CLAIM_LEASE_MS).toISOString();
  const candidates = repo.claimCandidatesQuery({ ...opts, stamp });
  const row = firstRow(await exec(candidates.sql, candidates.params));
  if (!row) return null;
  const lease = repo.leaseEnrichJobQuery({ stamp, leaseUntil, id: row.id });
  const { rowCount } = await exec(lease.sql, lease.params);
  if (!Number(rowCount)) return null;
  const byId = repo.enrichJobByIdQuery(row.id);
  return firstRow(await exec(byId.sql, byId.params));
}

async function claimEnrichJobsViaExec(exec, { limit = 6 } = {}, now = Date.now()) {
  const reclaim = repo.reclaimStaleEnrichJobsQuery(new Date(now).toISOString());
  await exec(reclaim.sql, reclaim.params);
  const cap = Math.max(1, Math.min(Number(limit) || 6, 12));
  const claimed = [];
  const seen = new Set();
  const take = async (opts, n) => {
    for (let i = 0; i < n; i += 1) {
      const row = await claimOneViaExec(exec, opts, now);
      if (!row || seen.has(row.id)) break;
      seen.add(row.id);
      claimed.push(row);
    }
  };
  for (const step of claimTakePlan(cap)) {
    await take(step.opts, step.slots < 0 ? cap - claimed.length : step.slots);
  }
  return claimed;
}

// listingEnrichQueue.js claimEnrichJobs()
export function claimEnrichJobsAsync(conn, { limit = 6 } = {}, options = {}) {
  const opts = withConn(options, conn);
  return withFallbackCounted(
    opts,
    (exec) => claimEnrichJobsViaExec(exec, { limit }),
    () => claimEnrichJobsSync(conn, { limit }),
  );
}

// listingEnrichQueue.js finishJob()：回 { stale, superseded, status }（與 sync 版同義）。
export function finishEnrichJobAsync(conn, job, patch = {}, options = {}) {
  const opts = withConn(options, conn);
  return withFallbackCounted(
    opts,
    async (exec) => {
      const runSeq = repo.enrichJobRunSeqQuery(job.id);
      const latest = firstRow(await exec(runSeq.sql, runSeq.params));
      const plan = finishEnrichPlan(job, patch, latest);
      if (plan.stale) return { stale: true };
      await exec(plan.sql, plan.params);
      return { stale: false, superseded: plan.superseded, status: plan.status };
    },
    () => finishEnrichJobSync(conn, job, patch),
  );
}


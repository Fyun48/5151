// PG 版的不可變性守衛。對應 contentDocuments.js:106 的 SQLite TRIGGER：
//   * `NEW.x IS NOT OLD.x` → `NEW.x IS DISTINCT FROM OLD.x`（PG 的 IS NOT 不能比 NULL）
//   * `RAISE(ABORT, …)` → `RAISE EXCEPTION '…'`（plpgsql）
//   * `CREATE TRIGGER IF NOT EXISTS` PG 沒有 ⇒ 先 DROP 再 CREATE（idempotent）
export const PG_IMMUTABLE_FUNCTION_SQL = `CREATE OR REPLACE FUNCTION content_documents_immutable_fn()
   RETURNS trigger AS $$
   BEGIN
     IF OLD.status = 'published' AND (
       NEW.body IS DISTINCT FROM OLD.body
       OR NEW.title IS DISTINCT FROM OLD.title
       OR NEW.format IS DISTINCT FROM OLD.format
       OR NEW.check_label IS DISTINCT FROM OLD.check_label
       OR NEW.content_hash IS DISTINCT FROM OLD.content_hash
       OR NEW.version IS DISTINCT FROM OLD.version
       OR NEW.document_type IS DISTINCT FROM OLD.document_type
     ) THEN
       RAISE EXCEPTION 'published_document_immutable';
     END IF;
     RETURN NEW;
   END;
   $$ LANGUAGE plpgsql`;
export const PG_DROP_TRIGGER_SQL = "DROP TRIGGER IF EXISTS content_documents_immutable ON content_documents";
export const PG_CREATE_TRIGGER_SQL =
  `CREATE TRIGGER content_documents_immutable BEFORE UPDATE ON content_documents
   FOR EACH ROW EXECUTE FUNCTION content_documents_immutable_fn()`;

const isPg = (options = {}) => (options.driver || resolveDbDriver()) === "postgres";
const firstRow = (rows) => (Array.isArray(rows) && rows.length ? rows[0] : null);
// PG 的 MAX()／COUNT() 是 bigint，node-pg 回字串。
const countOf = (rows) => Number(firstRow(rows)?.n) || 0;

async function pgExec(options = {}) {
  if (options.exec) return options.exec;
  const pgDriver = options.pgDriver || (await sharedPgDriver());
  return (sql, params = []) => pgDriver.query(toPostgresSql(sql), params).then((res) => res.rows);
}

// 每個 pgDriver 只建一次 schema。沿用 budgetGuardAsync／listingToolsAsync／memberMediaAsync 的形狀。
const schemaReady = new WeakMap();
export async function ensureContentDocumentStoreOnce(pgDriver) {
  if (!pgDriver) return;
  if (schemaReady.has(pgDriver)) return schemaReady.get(pgDriver);
  const ready = (async () => {
    for (const sql of PG_SCHEMA_STATEMENTS) await pgDriver.exec(sql);
    await pgDriver.exec(PG_IMMUTABLE_FUNCTION_SQL);
    await pgDriver.exec(PG_DROP_TRIGGER_SQL);
    await pgDriver.exec(PG_CREATE_TRIGGER_SQL);
  })();
  schemaReady.set(pgDriver, ready);
  try {
    await ready;
  } catch (error) {
    schemaReady.delete(pgDriver); // 失敗不要快取，下次再試
    throw error;
  }
}

async function pgHandle(options = {}) {
  const exec = await pgExec(options);
  if (!options.exec) await ensureContentDocumentStoreOnce(options.pgDriver || (await sharedPgDriver()));
  return exec;
}

async function withFallback(options, runPostgres, runSqlite) {
  if (!isPg(options)) return runSqlite();
  try {
    return await runPostgres(await pgHandle(options));
  } catch (error) {
    if (!sqliteFallbackAllowed(options)) throw error;
    return runSqlite();
  }
}

async function withFallbackTx(options, runPostgres, runSqlite) {
  if (!isPg(options)) return runSqlite();
  try {
    if (options.exec) return await runPostgres(options.exec);
    const pgDriver = options.pgDriver || (await sharedPgDriver());
    await ensureContentDocumentStoreOnce(pgDriver);
    return await pgDriver.withTransaction(async (client) => {
      const exec = (sql, params = []) => client.query(toPostgresSql(sql), params).then((res) => res.rows);
      return runPostgres(exec);
    });
  } catch (error) {
    if (!sqliteFallbackAllowed(options, { write: true })) throw error;
    return runSqlite();
  }
}

// 稽核事件：同步版是 `audit()`。參數組法共用 `auditEventParams()`（含 `iso(now)`），
// 所以只有 SQL 那一句是新的。
async function writeAudit(exec, entry) {
  await exec(INSERT_EVENT_SQL, auditEventParams(entry));
}

const readById = async (exec, id) => rowToDoc(firstRow(await exec(DOC_BY_ID_SQL, [Number(id) || 0])));
const readByTypeVersion = async (exec, type, version) =>
  rowToDoc(firstRow(await exec(DOC_BY_TYPE_VERSION_SQL, [assertType(type), Number(version) || 0])));

async function nextVersionAsync(exec, type) {
  return countOf(await exec(NEXT_VERSION_SQL, [type])) + 1;
}

// ---- 讀取 ----

export async function listDocumentsAsync({ type, includeDrafts = false } = {}, options = {}) {
  return withFallback(
    options,
    async (exec) => {
      const rows = type
        ? await exec(LIST_BY_TYPE_SQL, [assertType(type)])
        : await exec(LIST_ALL_SQL);
      return rows.map(rowToDoc).filter((doc) => includeDrafts || doc.status === "published");
    },
    () => listDocumentsSync(sqliteHandle(), { type, includeDrafts }),
  );
}

export async function getDocumentByIdAsync(id, options = {}) {
  return withFallback(
    options,
    (exec) => readById(exec, id),
    () => getDocumentByIdSync(sqliteHandle(), id),
  );
}

export async function getEffectiveDocumentAsync(type, { now = new Date(), ...options } = {}) {
  return withFallback(
    options,
    async (exec) => {
      const id = assertType(type);
      const nowIso = iso(now);
      const rows = (await exec(PUBLISHED_BY_TYPE_SQL, [id])).map(rowToDoc);
      return rows.find((doc) => inEffect(doc, nowIso)) || null;
    },
    () => getEffectiveDocumentSync(sqliteHandle(), type, { now }),
  );
}

export async function getRequiredRegistrationDocumentsAsync({ now = new Date(), ...options } = {}) {
  if (!isPg(options)) return getRequiredRegistrationDocumentsSync(sqliteHandle(), { now });
  const out = [];
  for (const type of REGISTRATION_DOC_TYPES) {
    const doc = await getEffectiveDocumentAsync(type, { now, ...options });
    if (doc) out.push(doc);
  }
  return out;
}

export async function listDocumentEventsAsync({ type, documentId, limit = 50 } = {}, options = {}) {
  const n = Math.min(200, Math.max(1, Number(limit) || 50));
  return withFallback(
    options,
    async (exec) => {
      if (documentId) return exec(EVENTS_BY_DOC_SQL, [Number(documentId), n]);
      if (type) return exec(EVENTS_BY_TYPE_SQL, [assertType(type), n]);
      return exec(EVENTS_ALL_SQL, [n]);
    },
    () => listDocumentEventsSync(sqliteHandle(), { type, documentId, limit }),
  );
}

// 多條路由的共用卡點（`/api/disclaimer`、`/api/me`、註冊流程…）。
export async function legalCopyFromDocumentsAsync({ now = new Date(), ...options } = {}) {
  if (!isPg(options)) return legalCopyFromDocumentsSync(sqliteHandle(), { now });
  const terms = await getEffectiveDocumentAsync("registration_terms", { now, ...options });
  const privacy = await getEffectiveDocumentAsync("privacy_notice", { now, ...options });
  const defaults = defaultLegalCopy();
  return {
    version: terms ? `v${terms.version}` : defaults.version,
    disclaimer: terms?.body || defaults.disclaimer,
    disclaimerCheck: terms?.check_label || defaults.disclaimerCheck,
    privacy: privacy?.body || defaults.privacy,
    privacyCheck: privacy?.check_label || defaults.privacyCheck,
    text: terms?.body || defaults.disclaimer,
    privacy_text: privacy?.body || defaults.privacy,
  };
}


// 意見回饋附圖（C3）的 driver-aware 入口（PG 島嶼）。
//
// 同步版的邏輯全部在 `feedbackMedia.js`；這裡只負責：
//   1. 走 PG 時把 SQL 翻成 PG 方言，並補建 schema（PG 的 `ADD COLUMN IF NOT EXISTS`）
//   2. 依 `sqliteFallbackAllowed()` 決定失敗時要不要回退本機 handle
//
// 附件**只寫本機檔案**（`DATA_DIR/feedback-media/`），所以檔案 I/O 兩個 driver 共用，
// 沒有 R2 物件要清（與 memberMedia 不同：那條路上傳時會推 CDN）。
//
// PG 的 demand/feedback 島嶼有 `withTransaction`（見 feedbackAsync.js）；附件 claim 會在
// 那個交易內執行，所以這裡另外提供吃 `exec` 的 `claimFeedbackAttachmentsAsync()`。

